BLOCKED_TOOLKITS = tuple(
    ToolkitSpec(
        key=module,
        label=module.replace("_", " ").title(),
        category="Blocked",
        description="Not exposed in the multi-tenant runtime.",
        module=module,
        class_name="",
        tier="blocked",
        disabled_reason="Blocked by the Atlas multi-tenant safety policy.",
        exposed=False,
    )
    for module in sorted(BLOCKED_MODULES)
)

TOOLKIT_SPECS = SAFE_TOOLKITS + CREDENTIAL_TOOLKITS + BLOCKED_TOOLKITS
TOOLKIT_BY_KEY = {item.key: item for item in TOOLKIT_SPECS}


def toolkit_availability(spec: ToolkitSpec) -> tuple[bool, str | None]:
    return _toolkit_availability(spec.key)


@cache
def _toolkit_availability(key: str) -> tuple[bool, str | None]:
    spec = TOOLKIT_BY_KEY[key]
    if spec.tier == "blocked" or spec.disabled_reason:
        return False, spec.disabled_reason
    try:
        module = importlib.import_module(f"agno.tools.{spec.module}")
        if not hasattr(module, spec.class_name):
            return False, f"Agno {spec.class_name} is not installed in this release."
        toolkit_type = getattr(module, spec.class_name)
        kwargs = {spec.credentials[0].kwarg: "atlas-availability-check"} if spec.credentials else {}
        toolkit_type(**kwargs)
    except Exception as exc:
        return False, spec.install_hint or str(exc)
    return True, None


def public_toolkit_catalog() -> list[dict[str, Any]]:
    result: list[dict[str, Any]] = []
    for spec in TOOLKIT_SPECS:
        available, reason = toolkit_availability(spec)
        item = asdict(spec)
        item["credentials"] = [asdict(credential) for credential in spec.credentials]
        item["available"] = available
        item["unavailable_reason"] = reason
        item["status"] = (
            "blocked"
            if spec.tier == "blocked"
            else "unavailable"
            if not available
            else "needs_credential"
            if spec.credentials
            else "ready"
        )
        result.append(item)
    return result
