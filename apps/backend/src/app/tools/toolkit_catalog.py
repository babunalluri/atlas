from __future__ import annotations

import importlib
from dataclasses import asdict, dataclass, field
from functools import cache
from typing import Any, Literal

SafetyTier = Literal["safe", "credential", "blocked"]


@dataclass(frozen=True, slots=True)
class CredentialSpec:
    env_var: str
    provider: str
    kwarg: str = "api_key"


@dataclass(frozen=True, slots=True)
class ToolkitSpec:
    key: str
    label: str
    category: str
    description: str
    module: str
    class_name: str
    tier: SafetyTier
    credentials: tuple[CredentialSpec, ...] = ()
    options: dict[str, dict[str, Any]] = field(default_factory=dict)
    side_effects: bool = False
    install_hint: str | None = None
    disabled_reason: str | None = None
    exposed: bool = True


def _credential(
    key: str,
    label: str,
    category: str,
    module: str,
    class_name: str,
    provider: str,
    env_var: str,
    *,
    kwarg: str = "api_key",
    description: str | None = None,
    side_effects: bool = False,
    hint: str | None = None,
    disabled: str | None = None,
) -> ToolkitSpec:
    return ToolkitSpec(
        key=key,
        label=label,
        category=category,
        description=description or f"Use {label} through its server-managed Agno toolkit.",
        module=module,
        class_name=class_name,
        tier="credential",
        credentials=(CredentialSpec(env_var, provider, kwarg),),
        side_effects=side_effects,
        install_hint=hint,
        disabled_reason=disabled,
    )


def _safe(
    key: str,
    label: str,
    category: str,
    module: str,
    class_name: str,
    description: str,
    *,
    options: dict[str, dict[str, Any]] | None = None,
    hint: str | None = None,
) -> ToolkitSpec:
    return ToolkitSpec(
        key=key,
        label=label,
        category=category,
        description=description,
        module=module,
        class_name=class_name,
        tier="safe",
        options=options or {},
        install_hint=hint,
    )


